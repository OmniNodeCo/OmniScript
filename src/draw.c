Canvas *canvas_new(int w, int h, const unsigned char bg[3]) {
    Canvas *c;
    int x, y;
    if (w < 1 || h < 1)
        return NULL;
    c = malloc(sizeof(Canvas));
    if (!c)
        return NULL;
    c->px = malloc((size_t)w * (size_t)h * 3);
    if (!c->px) {
        free(c);
        return NULL;
    }
    c->w = w;
    c->h = h;
    for (y = 0; y < h; y++) {
        for (x = 0; x < w; x++) {
            unsigned char *p = c->px + ((size_t)y * (size_t)w + (size_t)x) * 3;
            p[0] = bg[0];
            p[1] = bg[1];
            p[2] = bg[2];
        }
    }
    return c;
}

void canvas_free(Canvas *c) {
    if (c) {
        free(c->px);
        free(c);
    }
}

static void set(Canvas *c, int x, int y, const unsigned char col[3]) {
    if (x >= 0 && y >= 0 && x < c->w && y < c->h) {
        unsigned char *p = c->px + ((size_t)y * (size_t)c->w + (size_t)x) * 3;
        p[0] = col[0];
        p[1] = col[1];
        p[2] = col[2];
    }
}

static void hline(Canvas *c, int x0, int x1, int y, const unsigned char col[3]) {
    int x, lo = x0 < x1 ? x0 : x1, hi = x0 < x1 ? x1 : x0;
    for (x = lo; x <= hi; x++)
        set(c, x, y, col);
}

void canvas_rect(Canvas *c, int x, int y, int w, int h,
                 const unsigned char col[3]) {
    int j;
    for (j = 0; j < h; j++)
        hline(c, x, x + w - 1, y + j, col);
}

void canvas_outline(Canvas *c, int x, int y, int w, int h,
                    const unsigned char col[3]) {
    int j;
    if (w < 1 || h < 1)
        return;
    hline(c, x, x + w - 1, y, col);
    hline(c, x, x + w - 1, y + h - 1, col);
    for (j = 0; j < h; j++) {
        set(c, x, y + j, col);
        set(c, x + w - 1, y + j, col);
    }
}

/* A filled disc, scanline by scanline, integer math only. */
void canvas_circle(Canvas *c, int cx, int cy, int r,
                   const unsigned char col[3]) {
    int dy;
    if (r < 0)
        return;
    for (dy = -r; dy <= r; dy++) {
        int dx = r;
        while (dx * dx + dy * dy > r * r)
            dx--;
        hline(c, cx - dx, cx + dx, cy + dy, col);
    }
}

static void dot(Canvas *c, int x, int y, int r, const unsigned char col[3]) {
    int dy;
    for (dy = -r; dy <= r; dy++) {
        int dx = r;
        while (dx * dx + dy * dy > r * r)
            dx--;
        hline(c, x - dx, x + dx, y + dy, col);
    }
}

void canvas_line(Canvas *c, int x1, int y1, int x2, int y2,
                 const unsigned char col[3], int width) {
    int dx = x2 - x1, dy = y2 - y1;
    int sx = dx >= 0 ? 1 : -1, sy = dy >= 0 ? 1 : -1;
    int adx = dx >= 0 ? dx : -dx, ady = dy >= 0 ? dy : -dy;
    int err = (adx > ady ? adx : -ady) / 2, e2;
    int x = x1, y = y1;
    int r = width > 0 ? width / 2 : 0;
    for (;;) {
        if (r)
            dot(c, x, y, r, col);
        else
            set(c, x, y, col);
        if (x == x2 && y == y2)
            break;
        e2 = err;
        if (e2 > -adx) {
            err -= ady;
            x += sx;
        }
        if (e2 < ady) {
            err += adx;
            y += sy;
        }
    }
}

int font_pixel(char c, int col, int row) {
    unsigned char u = (unsigned char)c;
    const char *g;
    if (u < 0x20 || u > 0x7e)
        g = FONT['?' - 0x20];
    else
        g = FONT[u - 0x20];
    return g[row * 5 + col] == '#';
}

static void glyph(Canvas *c, int x, int y, char ch,
                  const unsigned char col[3], int scale) {
    int r, q;
    for (r = 0; r < 7; r++) {
        for (q = 0; q < 5; q++) {
            if (font_pixel(ch, q, r)) {
                int dy, dx;
                for (dy = 0; dy < scale; dy++) {
                    for (dx = 0; dx < scale; dx++)
                        set(c, x + q * scale + dx, y + r * scale + dy, col);
                }
            }
        }
    }
}

static int text_scale(int size) {
    if (size < 7)
        return 1;
    return size / 7;
}

void canvas_text(Canvas *c, int x, int y, const char *msg,
                 const unsigned char col[3], int size) {
    int i = 0, scale = text_scale(size);
    for (; msg[i]; i++)
        glyph(c, x + i * 6 * scale, y, msg[i], col, scale);
}

int canvas_text_width(const char *msg, int size) {
    return (int)strlen(msg) * 6 * text_scale(size);
}

/* ------------------------------------------------------------- BMP output */
static void put_u16(unsigned char *p, unsigned v) {
    p[0] = (unsigned char)(v & 0xff);
    p[1] = (unsigned char)((v >> 8) & 0xff);
}

static void put_u32(unsigned char *p, unsigned long v) {
    p[0] = (unsigned char)(v & 0xff);
    p[1] = (unsigned char)((v >> 8) & 0xff);
    p[2] = (unsigned char)((v >> 16) & 0xff);
    p[3] = (unsigned char)((v >> 24) & 0xff);
}

int img_write_bmp(const char *path, const Canvas *c) {
    FILE *f;
    unsigned char head[54];
    unsigned long stride, img_size, file_size;
    int y;
    if (!c || c->w < 1 || c->h < 1)
        return -1;
    stride = ((unsigned long)c->w * 3 + 3) & ~3ul;
    img_size = stride * (unsigned long)c->h;
    file_size = 54 + img_size;
    memset(head, 0, sizeof(head));
    head[0] = 'B';
    head[1] = 'M';
    put_u32(head + 2, file_size);
    put_u32(head + 10, 54);
    put_u32(head + 14, 40);
    put_u32(head + 18, (unsigned long)c->w);
    put_u32(head + 22, (unsigned long)c->h);
    put_u16(head + 26, 1);
    put_u16(head + 28, 24);
    put_u32(head + 34, img_size);
    f = fopen(path, "wb");
    if (!f)
        return -1;
    if (fwrite(head, 1, 54, f) != 54) {
        fclose(f);
        return -1;
    }
    for (y = c->h - 1; y >= 0; y--) {
        const unsigned char *row = c->px + (size_t)y * (size_t)c->w * 3;
        int x;
        for (x = 0; x < c->w; x++) {
            unsigned char bgr[3] = { row[x * 3 + 2], row[x * 3 + 1], row[x * 3] };
            if (fwrite(bgr, 1, 3, f) != 3) {
                fclose(f);
                return -1;
            }
        }
        {
            unsigned long pad = stride - (unsigned long)c->w * 3;
            unsigned long k;
            for (k = 0; k < pad; k++) {
                if (fputc(0, f) == EOF) {
                    fclose(f);
                    return -1;
                }
            }
        }
    }
    if (fclose(f) != 0)
        return -1;
    return 0;
}

